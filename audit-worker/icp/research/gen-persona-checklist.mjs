// Generates audit-worker/src/checklist-persona.ts from the approved persona
// point lists in icp/research/selected/*.jsonl (PERSONA-POINTS-PROPOSAL.md).
// Re-run after editing a list:  node icp/research/gen-persona-checklist.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const read = f => fs.readFileSync(path.join(here, f), "utf8").split(/\r?\n/).filter(Boolean).map(JSON.parse);

// Current GA4 points whose status code decides (ga4-facts.ts). A persona point
// built on one of them keeps that fact.
const FACT_IDS = new Set(read("existing-index.jsonl").filter(p => p.fact && p.pid.startsWith("EXIST-GA4-")).map(p => p.pid.replace("EXIST-", "")));

const NEW_FACTS = fs.existsSync(path.join(here, "new-fact-map.json")) ? JSON.parse(fs.readFileSync(path.join(here, "new-fact-map.json"), "utf8")) : {};

const PERSONAS = { store_owner: ["store-owner", "SO"], media_buyer: ["media-buyer", "MB"] };
const SECTIONS = ["GA4", "GTM", "WEBCODE", "CRO", "CLARITY"];
const SEVERITIES = new Set(["critical", "medium", "low"]);
const OPPORTUNITIES = new Set(["revenue_gain", "revenue_loss", "risk", "benefit"]);
const OWNERS = new Set(["dev", "marketing", "content", "owner"]);
const AD_EFFECTS = new Set(["performance", "aov", "cost", "inflated", "deflated", "optimization"]);
const SIGNAL_EFFECTS = new Set(["inflated", "deflated", "optimization"]);

const groupLabels = {};
const sharedSources = {};
const adEffects = {};
const lanes = {};
const lists = {};

for (const [role, [file, prefix]] of Object.entries(PERSONAS)) {
  lists[role] = {};
  for (const section of SECTIONS) {
    const rows = read(`selected/${file}-${section}.jsonl`).sort((a, b) => a.rank - b.rank);
    lists[role][section] = rows.map(r => {
      const group = `${prefix.toLowerCase()}-${String(r.group || section).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")}`;
      if (!groupLabels[group]) groupLabels[group] = { en: r.group_en || r.group || section, ar: r.group_ar || r.group_en || section };
      // A point that needs a new query (new_fact, e.g. paid-only splits) measures
      // something today's fact doesn't, so it never inherits that fact's status.
      // Points that needed a new query use the fact built for them (GA4-Pnn,
      // new-fact-map.json); the rest keep the shared fact they came from.
      const factId = section !== "GA4" ? undefined
        : NEW_FACTS[r.id] ?? (r.fact && !r.new_fact ? (r.sources || []).map(s => String(s).replace("EXIST-", "")).find(s => FACT_IDS.has(s)) : undefined);
      const shared = (r.sources || []).map(String).filter(s => s.startsWith("EXIST-")).map(s => s.replace("EXIST-", ""));
      if (shared.length) sharedSources[r.id] = shared;
      const effect = AD_EFFECTS.has(r.ad_effect) ? r.ad_effect : null;
      if (role === "media_buyer" && effect) {
        adEffects[r.id] = effect;
        lanes[r.id] = SIGNAL_EFFECTS.has(effect) ? "signal" : "post_click";
      }
      const owners = (r.owners || []).filter(o => OWNERS.has(o));
      return {
        id: r.id,
        group,
        title: r.title,
        severity: SEVERITIES.has(r.severity) ? r.severity : r.severity === "high" ? "critical" : "medium",
        opportunity: OPPORTUNITIES.has(r.opportunity) ? r.opportunity : "risk",
        owners: owners.length ? owners : ["dev"],
        expectedState: r.pass,
        commonFailure: r.fails,
        validate: r.validate,
        action: r.action,
        doneWhen: r.done_when,
        whyItMatters: r.why_it_matters,
        measuredBy: r.measured_by,
        ...(factId && { fact: true, factId }),
        ...(r.measured_by === "browser" && { browser: true }),
      };
    });
  }
}

const out = `// GENERATED by icp/research/gen-persona-checklist.mjs from the approved
// persona lists (icp/PERSONA-POINTS-PROPOSAL.md). Don't edit by hand: edit
// icp/research/selected/*.jsonl and re-run the generator.
//
// One checklist per persona, in four sections plus Clarity. Which sections an
// audit runs follows the same three routes as the shared lists
// (persona-checklist.ts's personaChecklistFor):
//   GA4 + GTM  -> GA4 25 + GTM 25
//   one tool   -> that tool's 25 + WEBCODE 25
//   neither    -> WEBCODE 25 + CRO 25
// CLARITY only runs when the visitor connected Clarity, outside the 50.
import type { ChecklistPoint } from "./checklist.js";

export type PersonaRole = "store_owner" | "media_buyer";
export type PersonaSection = "GA4" | "GTM" | "WEBCODE" | "CRO" | "CLARITY";

export interface PersonaChecklistPoint extends ChecklistPoint {
  // The GA4 fact (ga4-facts.ts) that decides this point's status, when it is
  // a rewrite of one of today's computed GA4 points.
  factId?: string;
  whyItMatters?: string;
  measuredBy?: string;
}

export const PERSONA_GROUP_LABELS: Record<string, { en: string; ar: string }> = ${JSON.stringify(groupLabels, null, 2)};

// The shared points (checklist.ts) each persona point was rewritten from, so
// code keyed on shared ids (reader-questions.ts) still finds them.
export const PERSONA_SHARED_SOURCES: Record<string, string[]> = ${JSON.stringify(sharedSources, null, 2)};

// Media buyer only: the ROAS/CAC direction of each point (ad-impact.ts).
export const PERSONA_AD_EFFECT: Record<string, "performance" | "aov" | "cost" | "inflated" | "deflated" | "optimization"> = ${JSON.stringify(adEffects, null, 2)};

// Media buyer only: "is the number real?" (signal) or "does paid traffic convert?" (post_click).
export const PERSONA_LANE: Record<string, "signal" | "post_click"> = ${JSON.stringify(lanes, null, 2)};

export const PERSONA_CHECKLISTS: Record<PersonaRole, Record<PersonaSection, PersonaChecklistPoint[]>> = ${JSON.stringify(lists, null, 2)};
`;

const target = path.join(here, "..", "..", "src", "checklist-persona-data.ts");
fs.writeFileSync(target, out);
const counts = Object.fromEntries(Object.entries(lists).map(([r, s]) => [r, Object.fromEntries(Object.entries(s).map(([k, v]) => [k, v.length]))]));
const facts = Object.values(lists).flatMap(s => Object.values(s).flat()).filter(p => p.fact).map(p => `${p.id}->${p.factId}`);
console.log(JSON.stringify(counts), "\nfacts kept:", facts.length, facts.join(" "));
